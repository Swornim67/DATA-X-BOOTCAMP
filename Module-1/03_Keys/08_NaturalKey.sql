-- Natural Key
-- A Natural Key uses real-world data to uniquely
-- identify each row.

-- Examples:
-- Passport number, National ID number, email address.

-- Example:
-- A passport number like 'NEP1020-190-2' can identify
-- a passport uniquely, so it can be used as a Natural Key.

-- Important Points:
-- 1. It has real-world meaning.
-- 2. It can uniquely identify a record.
-- 3. It can be a Primary Key or a UNIQUE key.
-- 4. It should not change frequently.