-- QUERIES.

-- SHOW THE VALID ORDERS WITH CUSTOMERS DETAILS 
select 
*
from customers c 
join orders o 
on c.customer_id=o.customer_id;


-- SHOW THE ORDER DETAILS WITH THE CUSTOMER NAME AND PRODUCT NAME
select 
c.customer_id,o.order_id,c.customer_name,p.product_name,o.order_amount
from customers c 
join orders o 
on c.customer_id=o.customer_id
join products p 
on o.product_id=p.product_id;


-- SHOW THE CUSTOMER NAME,CUSTOMER DETAILS, ORDER DETAILS, PAYMENT MODE AND PRODUCT
select 
c.customer_id,c.customer_name,o.order_id,o.order_amount,p.product_name,pay.payment_mode,pay.payment_status
from customers c 
join orders o 
on c.customer_id=o.customer_id
join products p 
on o.product_id=p.product_id
join payments pay 
on pay.order_id=o.order_id;	


-- AGGREGATION SCENARIO 

-- FIND THE TOTAL REVENUE GENERATED BY THE CITY.
select 
c.city,sum(o.order_amount) as total_revenue
from customers c 
join orders o 
on c.customer_id=o.customer_id
group by c.city;