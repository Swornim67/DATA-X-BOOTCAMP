-- INNER JOIN 

-- The Most used join in the SQL.

-- In this Join, It shows the matching records or common records between tables as per the joining key.

-- In simple words, it shows us the intersection between 2 tables.


-- creating a database for the practice

create database Inner_Join;

-- using the database.

use Inner_Join;

-- creating table in the Joins_Practice database.

-- DDL FOR THE CUSTOMERS TABLE 
create table if not exists customers
(
customer_id int primary key,
customer_name varchar(50),
city varchar(50),
signup_date date
);

-- DDL FOR THE PRODUCT TABLE 
create table if not exists products
(
product_id int primary key,
product_name varchar(50) NOT NULL,
category varchar(50)
);

-- DDL FOR THE ORDERS TABLE 
create table if not exists orders
(
order_id int primary key,
customer_id int,
product_id int,
order_amount decimal(10,2),
order_date date,
order_status varchar(50)
);


-- DDL FOR THE PAYMENTS TABLE 
create table if not exists payments
(
payment_id int primary key,
order_id int,
Payment_mode varchar(50),
payment_status varchar(50),
paid_amount decimal (10,2),
payment_date date
);


