# Interview Questions and Answers

-- Q1. What is FULL OUTER JOIN?

# FULL OUTER JOIN RETURNS ALL ROWS FROM BOTH TABLES, WHETHER THEY MATCH OR NOT.
# IT RETURNS MATCHING ROWS AND UNMATCHED ROWS FROM BOTH TABLES.

-- Q2. Where is FULL OUTER JOIN used?

# FULL OUTER JOIN IS USED IN SOURCE VS TARGET VALIDATION,
# REPORT COMPARISON, AND MIGRATED DATA VALIDATION.

-- Q3. Does MySQL support FULL OUTER JOIN?

# NO, MYSQL DOES NOT SUPPORT FULL OUTER JOIN DIRECTLY.
# WE CAN EMULATE IT USING LEFT JOIN, RIGHT JOIN, AND UNION.

-- Q4. What is CROSS JOIN?

# CROSS JOIN RETURNS EVERY POSSIBLE COMBINATION OF ROWS FROM TWO TABLES.
# IT IS ALSO CALLED A CARTESIAN PRODUCT.

-- Q5. When is CROSS JOIN useful?

# CROSS JOIN IS USEFUL FOR PRODUCT-STORE COMBINATIONS,
# DATA-PRODUCT COMBINATIONS, AND GENERATING ALL POSSIBLE COMBINATIONS.

-- Q6. Why can CROSS JOIN be dangerous?

# CROSS JOIN CAN PRODUCE A VERY LARGE NUMBER OF ROWS
# WHEN THE TABLES CONTAIN MANY RECORDS, WHICH CAN AFFECT PERFORMANCE.

-- Q7. What is SELF JOIN?

# SELF JOIN IS A JOIN IN WHICH A TABLE JOINS WITH ITSELF
# USING DIFFERENT ALIASES.

-- Q8. Is SELF JOIN a separate SQL keyword?

# NO, SELF JOIN IS NOT A SEPARATE JOIN KEYWORD.
# IT IS A TECHNIQUE OF JOINING A TABLE WITH ITSELF.

-- Q9. Why do we use LEFT JOIN in employee-manager SELF JOIN?

# WE USE LEFT JOIN TO SHOW EVERY EMPLOYEE,
# INCLUDING EMPLOYEES WHO DO NOT HAVE A MANAGER.
# IF NO MANAGER EXISTS, THE MANAGER COLUMNS RETURN NULL.

-- Q10. What is NON-EQUI JOIN?

# NON-EQUI JOIN IS A JOIN THAT USES CONDITIONS SUCH AS >, <, >=, <=,
# OR BETWEEN INSTEAD OF ONLY THE EQUALS (=) OPERATOR.

-- Q11. Where is NON-EQUI JOIN used?

# NON-EQUI JOIN IS USED IN SALARY BANDS, TAX SLABS,
# AGE GROUPS, AND RANGE-BASED COMPARISONS.

-- Q12. What is SEMI JOIN?

# SEMI JOIN RETURNS ROWS FROM THE FIRST TABLE
# WHEN A MATCHING ROW EXISTS IN THE SECOND TABLE.
# IT RETURNS COLUMNS ONLY FROM THE FIRST TABLE.

-- Q13. What is ANTI JOIN?

# ANTI JOIN RETURNS ROWS FROM THE FIRST TABLE
# WHEN NO MATCHING ROW EXISTS IN THE SECOND TABLE.

-- Q14. Difference between SEMI JOIN and INNER JOIN?

# SEMI JOIN: RETURNS ROWS FROM THE FIRST TABLE WHEN A MATCH EXISTS.
# IT DOES NOT DUPLICATE FIRST-TABLE ROWS BECAUSE OF MULTIPLE MATCHES.

# INNER JOIN: RETURNS MATCHING ROWS FROM BOTH TABLES.
# MULTIPLE MATCHES CAN PRODUCE MULTIPLE OUTPUT ROWS.

-- Q15. Difference between ANTI JOIN and LEFT JOIN?

# ANTI JOIN: RETURNS ROWS FROM THE FIRST TABLE THAT HAVE NO MATCH
# IN THE SECOND TABLE.

# LEFT JOIN: RETURNS ALL ROWS FROM THE FIRST TABLE
# AND MATCHING ROWS FROM THE SECOND TABLE.
# IF NO MATCH EXISTS, THE SECOND-TABLE COLUMNS RETURN NULL.

-- Q16. Why should we avoid NOT IN when NULL exists?

# WE SHOULD BE CAREFUL WITH NOT IN WHEN THE SUBQUERY RETURNS NULL,
# BECAUSE COMPARISONS CAN BECOME UNKNOWN AND UNEXPECTEDLY FILTER OUT ROWS.
# WE CAN USE NOT EXISTS OR FILTER NULL USING IS NOT NULL.

-- Q17. What is NATURAL JOIN?

# NATURAL JOIN AUTOMATICALLY JOINS TWO TABLES USING ALL COLUMNS
# THAT HAVE THE SAME NAMES, WITHOUT AN ON CONDITION.

-- Q18. Why is NATURAL JOIN avoided in production?

# NATURAL JOIN IS OFTEN AVOIDED IN PRODUCTION BECAUSE ITS JOIN CONDITIONS
# ARE AUTOMATICALLY SELECTED AND MAY CHANGE WHEN THE TABLE SCHEMA CHANGES.
# IF NO COMMON COLUMN NAMES EXIST, IT PRODUCES A CARTESIAN PRODUCT.